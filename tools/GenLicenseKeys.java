import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.KeyPair;
import java.security.KeyPairGenerator;
import java.util.Base64;

/** Generate the RSA key pair used by the activation code service. */
public final class GenLicenseKeys {
    public static void main(String[] args) throws Exception {
        Path root = Path.of(args[0]);
        Path keyDir = root.resolve("server/whzs/keys");
        Path kotlinDir = root.resolve("app/src/main/java/cn/lhup/wechatmood/core");
        Files.createDirectories(keyDir);
        Files.createDirectories(kotlinDir);

        KeyPairGenerator generator = KeyPairGenerator.getInstance("RSA");
        generator.initialize(2048);
        KeyPair pair = generator.generateKeyPair();

        String privatePem = pem("PRIVATE KEY", pair.getPrivate().getEncoded());
        String publicPem = pem("PUBLIC KEY", pair.getPublic().getEncoded());

        write(keyDir.resolve("private.pem"), privatePem);
        write(keyDir.resolve("public.pem"), publicPem);
        write(kotlinDir.resolve("LicenseKeys.kt"),
            "package cn.lhup.wechatmood.core\n\n"
                + "/** Generated by tools/license-keys.ps1. Do not edit manually. */\n"
                + "object LicenseKeys {\n"
                + "    const val PUBLIC_KEY_PEM = \"\"\"\n"
                + publicPem + "\n"
                + "\"\"\"\n"
                + "}\n");

        System.out.println("RSA key pair generated.");
        System.out.println("  private key: server/whzs/keys/private.pem (server only)");
        System.out.println("  public key : server/whzs/keys/public.pem + LicenseKeys.kt");
        System.out.println("WARNING: regenerating invalidates all existing activation codes.");
    }

    private static String pem(String label, byte[] der) {
        String body = Base64.getMimeEncoder(64, "\n".getBytes(StandardCharsets.US_ASCII)).encodeToString(der);
        return "-----BEGIN " + label + "-----\n" + body + "\n-----END " + label + "-----";
    }

    private static void write(Path path, String text) throws IOException {
        Files.writeString(path, text, StandardCharsets.UTF_8);
    }
}
